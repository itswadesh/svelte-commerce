#!/usr/bin/env node
/**
 * Keeps the TYPE layer in step with whichever backend connector package.json installs.
 *
 * `@misiki/kitcommerce-core` names `@misiki/litekart-connector` in its own type barrel
 * (dist/services/types/index.d.ts: `export type * from '@misiki/litekart-connector'`), and
 * `export type *` cannot take anything but a literal specifier. On a storefront that swapped
 * connectors that package isn't installed, so the domain types (Product, Cart, Category, Menu,
 * CartLineItem, ...) silently resolve to nothing and `npm run check` reports them missing —
 * `skipLibCheck` hides the unresolved import but not its consequences.
 *
 * vite.config.ts solves the same problem for the runtime/bundling layer with a resolver plugin;
 * TypeScript has no equivalent hook, so this writes an ambient declaration that maps the litekart
 * specifier onto the installed connector. Every @misiki connector is a fork exposing the same
 * surface, so the redirect is type-safe.
 *
 * Generated, not committed. Run by `npm run check`. Safe to run at any time: with litekart
 * installed (or no single connector to point at) it removes the file instead, so the real package
 * is never shadowed.
 */
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const LITEKART_CONNECTOR = '@misiki/litekart-connector'
const CONNECTOR_NAME = /^@misiki\/[a-z0-9-]+-connector$/
const OUT_DIR = join(root, 'src', 'lib', 'core', 'connectors')
const OUT_FILE = join(OUT_DIR, 'connector-types.d.ts')

const activeConnector = () => {
	const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
	const names = Object.keys({ ...pkg.dependencies, ...pkg.devDependencies }).filter((name) =>
		CONNECTOR_NAME.test(name)
	)
	return names.length === 1 ? names[0] : null
}

// Nothing to redirect: litekart is installed under its own name, or there is no single connector
// to choose. Drop any file left over from a previous connector so it can't shadow the real one.
const clear = () => {
	if (existsSync(OUT_FILE)) {
		rmSync(OUT_FILE)
		console.log(`removed ${OUT_FILE} (no connector redirect needed)`)
	}
}

const connector = activeConnector()

if (!connector || connector === LITEKART_CONNECTOR) {
	clear()
} else if (!existsSync(OUT_DIR)) {
	// Install-time run before sources are present (e.g. a Docker layer that copies package.json
	// first). Types aren't checked there, and `npm run check` regenerates this later.
	console.log(`skipped: ${OUT_DIR} does not exist yet`)
} else {
	writeFileSync(
		OUT_FILE,
		`// GENERATED by sync-connector-types.js — do not edit, do not commit.
//
// @misiki/kitcommerce-core's type barrel imports '${LITEKART_CONNECTOR}' by name, but this
// storefront installs ${connector}. Redirect the specifier so the domain types resolve.
declare module '${LITEKART_CONNECTOR}' {
\texport * from '${connector}'
}
`,
		'utf8'
	)
	console.log(`wrote ${OUT_FILE} -> ${connector}`)
}
